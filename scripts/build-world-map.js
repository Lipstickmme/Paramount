'use strict';

/**
 * Turns Natural Earth land polygons into the SVG path the fleet map draws.
 *
 * Run when the source data changes; the output is committed, so the site never
 * fetches a map at runtime:
 *
 *   node scripts/build-world-map.js path/to/ne_110m_land.geojson
 *
 * Source: Natural Earth 110m land (public domain), from
 * https://github.com/nvkelso/natural-earth-vector
 *
 * The projection is equirectangular and deliberately cropped to the latitudes
 * ships actually work in: the poles are mostly empty ocean and Antarctica, and
 * cutting them makes every trade lane bigger on the same plate.
 */

const fs = require('fs');
const path = require('path');

const SRC = process.argv[2];
const OUT = path.join(__dirname, '..', 'public', 'assets', 'map', 'world.js');
// The same geometry as data, for the build step that renders the network page
// server-side. One source, two consumers.
const OUT_JSON = path.join(__dirname, '..', 'src', 'data', 'world-map.json');

const W = 1000;
const LAT_MAX = 79;
const LAT_MIN = -58;
const H = Math.round((W * (LAT_MAX - LAT_MIN)) / 360);

const x = (lng) => ((Number(lng) + 180) / 360) * W;
const y = (lat) => ((LAT_MAX - Number(lat)) / (LAT_MAX - LAT_MIN)) * H;

/** Rough degree-squared extent, used to drop specks that only add bytes. */
function extent(ring) {
  let minX = Infinity;
  let maxX = -Infinity;
  let minY = Infinity;
  let maxY = -Infinity;
  ring.forEach(([lng, lat]) => {
    if (lng < minX) minX = lng;
    if (lng > maxX) maxX = lng;
    if (lat < minY) minY = lat;
    if (lat > maxY) maxY = lat;
  });
  return (maxX - minX) * (maxY - minY);
}

/**
 * Perpendicular-distance simplification (Douglas-Peucker).
 *
 * The 110m source is already coarse, but coastlines still carry more points
 * than a 1000px-wide plate can show, and every one of them is bytes on every
 * page load.
 */
function simplify(points, tolerance) {
  if (points.length < 3) return points;

  const sqTol = tolerance * tolerance;
  const sqSegDist = ([px, py], [ax, ay], [bx, by]) => {
    let nx = ax;
    let ny = ay;
    let dx = bx - nx;
    let dy = by - ny;
    if (dx !== 0 || dy !== 0) {
      const t = ((px - nx) * dx + (py - ny) * dy) / (dx * dx + dy * dy);
      if (t > 1) {
        nx = bx;
        ny = by;
      } else if (t > 0) {
        nx += dx * t;
        ny += dy * t;
      }
    }
    dx = px - nx;
    dy = py - ny;
    return dx * dx + dy * dy;
  };

  const keep = new Array(points.length).fill(false);
  keep[0] = true;
  keep[points.length - 1] = true;
  const stack = [[0, points.length - 1]];

  while (stack.length) {
    const [first, last] = stack.pop();
    let index = -1;
    let furthest = sqTol;
    for (let i = first + 1; i < last; i += 1) {
      const d = sqSegDist(points[i], points[first], points[last]);
      if (d > furthest) {
        furthest = d;
        index = i;
      }
    }
    if (index > 0) {
      keep[index] = true;
      stack.push([first, index], [index, last]);
    }
  }

  return points.filter((_, i) => keep[i]);
}

function ringToPath(ring) {
  // Clip to the drawn band rather than letting Antarctica stretch off-plate.
  const projected = ring
    .map(([lng, lat]) => [x(lng), y(Math.max(LAT_MIN, Math.min(LAT_MAX, lat)))])
    .filter(([px, py], i, all) => {
      if (i === 0) return true;
      const [qx, qy] = all[i - 1];
      return Math.abs(px - qx) > 0.35 || Math.abs(py - qy) > 0.35;
    });

  const points = simplify(projected, 0.55);
  if (points.length < 3) return '';

  const round = (n) => Math.round(n * 10) / 10;
  return (
    `M${round(points[0][0])} ${round(points[0][1])}` +
    points.slice(1).map(([px, py]) => `L${round(px)} ${round(py)}`).join('') +
    'Z'
  );
}

const geo = JSON.parse(fs.readFileSync(SRC, 'utf8'));
const rings = [];

geo.features.forEach((feature) => {
  const { type, coordinates } = feature.geometry;
  const polygons = type === 'Polygon' ? [coordinates] : coordinates;
  polygons.forEach((polygon) => {
    // [0] is the outer ring; holes (inland seas) are not worth the bytes here.
    const ring = polygon[0];
    if (extent(ring) < 1.2) return;
    const d = ringToPath(ring);
    if (d) rings.push(d);
  });
});

const body = `'use strict';

/* Generated by scripts/build-world-map.js from Natural Earth 110m land data
   (public domain). Equirectangular, cropped to ${LAT_MIN}..${LAT_MAX} degrees of
   latitude — the band ships actually work in. Do not edit by hand. */

window.PARAMOUNT_WORLD = {
  width: ${W},
  height: ${H},
  latMax: ${LAT_MAX},
  latMin: ${LAT_MIN},
  /** Longitude/latitude to plate coordinates. */
  project(lng, lat) {
    return {
      x: ((Number(lng) + 180) / 360) * ${W},
      y: ((${LAT_MAX} - Math.max(${LAT_MIN}, Math.min(${LAT_MAX}, Number(lat)))) / ${LAT_MAX - LAT_MIN}) * ${H},
    };
  },
  land: '${rings.join('')}',
};
`;

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, body, 'utf8');

fs.writeFileSync(
  OUT_JSON,
  JSON.stringify({ width: W, height: H, latMax: LAT_MAX, latMin: LAT_MIN, land: rings.join('') }),
  'utf8'
);

console.log(`[world] ${rings.length} landmasses, ${(body.length / 1024).toFixed(1)} KB -> public/assets/map/world.js + src/data/world-map.json`);
